def fill_placeholders(text: str, values: dict[str, str], source: str) -> str:
    missing: list[str] = []

    def repl(match: re.Match[str]) -> str:
        key, default = match.group(1), match.group(2)
        if key in values and values[key] != "":
            return str(values[key])
        if default is not None:
            return default
        missing.append(key)
        return match.group(0)

    filled = PLACEHOLDER_RE.sub(repl, text)
    leftover = PLACEHOLDER_RE.findall(filled)
    if missing or leftover:
        names = ", ".join(sorted(set(missing) | {k for k, _ in leftover}))
        raise SystemExit(f"Unfilled placeholders in {source}: {names}")
    return filled


def fill_role_file(src: Path, values: dict[str, str]) -> str:
    body = fill_placeholders(read(src), values, src.name)
    text = EXAMPLE_MARKER + "\n\n" + body
    if not text.endswith("\n"):
        text += "\n"
    return text


def expected_examples() -> dict[str, str]:
    files: dict[str, str] = {}
    for name in ("minimal", "realistic"):
        values_path = ROOT / "examples" / name / "placeholders.json"
        values = json.loads(values_path.read_text(encoding="utf-8"))
        prefix = f"examples/{name}"
        files[f"{prefix}/TEAM_CHARTER.md"] = fill_role_file(CHARTER, values)
        files[f"{prefix}/ESCALATION_ADR.md"] = fill_role_file(ADR, values)
        files[f"{prefix}/AGENTS.md"] = fill_role_file(CODER, values)
    return files


def write_files(files: dict[str, str]) -> list[str]:
    written = []
    for rel, content in files.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        path.write_text(content, encoding="utf-8")
        written.append(rel)
    return written


def check_files(files: dict[str, str]) -> list[str]:
    stale = []
    for rel, content in files.items():
        path = ROOT / rel
        if not path.exists():
            stale.append(f"{rel} (missing)")
            continue
        if path.read_text(encoding="utf-8") != content:
            stale.append(rel)
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if generated files are stale, without writing",
    )
    args = parser.parse_args(argv)
    files = expected_files()
    if args.check:
        stale = check_files(files)
        if stale:
            print("Generated files are stale or missing:", file=sys.stderr)
            for item in stale:
                print(f"  {item}", file=sys.stderr)
            print("Run: python3 scripts/generate_templates.py", file=sys.stderr)
            return 1
        print(f"generate_templates: {len(files)} files in sync")
        return 0
    written = write_files(files)
    if written:
        print("Updated:")
        for item in written:
            print(f"  {item}")
    else:
        print("All generated files already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
