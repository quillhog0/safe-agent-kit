def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def split_h2_sections(text: str) -> tuple[str, list[tuple[str, str]]]:
    """Return (preamble, [(heading, section_text_including_heading)])."""
    lines = text.splitlines(keepends=True)
    preamble: list[str] = []
    sections: list[tuple[str, list[str]]] = []
    current: tuple[str, list[str]] | None = None
    for line in lines:
        if line.startswith("## "):
            if current is not None:
                sections.append((current[0], "".join(current[1])))
            heading = line[3:].strip()
            current = (heading, [line])
        elif current is not None:
            current[1].append(line)
        else:
            preamble.append(line)
    if current is not None:
        sections.append((current[0], "".join(current[1])))
    return "".join(preamble), sections


def owner_intro(preamble: str) -> str:
    """Take the owner / workdir line only.

    The charter also says "Put this file at the repo root", which would be
    misleading inside an IDE template that is not TEAM_CHARTER.md.
    """
    for line in preamble.splitlines():
        if "only human approver" in line or "OWNER_NAME" in line:
            return line.lstrip("> ").strip()
    return ""


def drop_leading_h1(text: str) -> str:
    return re.sub(r"^# [^\n]+\n+", "", text.lstrip())


def shared_rules_markdown() -> str:
    preamble, sections = split_h2_sections(read(CHARTER))
    intro = owner_intro(preamble)
    parts: list[str] = []
    if intro:
        parts.append(intro)
        parts.append("")
    for _heading, body in sections:
        parts.append(body.rstrip())
        parts.append("")
    adr_body = drop_leading_h1(read(ADR)).rstrip()
    parts.append("## Escalation and ADRs")
    parts.append("")
    parts.append(adr_body)
    parts.append("")
    parts.append(FOOTNOTE)
    parts.append("")
    return "\n".join(parts)


def yaml_doc(frontmatter: str, title: str, lead: str, role: str, footer: str = "") -> str:
    parts: list[str] = []
    if frontmatter:
        parts.append("---")
        parts.append(frontmatter.rstrip())
        parts.append("---")
        parts.append("")
    parts.append(GENERATED_MARKER)
    parts.append("")
    if title:
        parts.append(f"# {title}")
        parts.append("")
    if lead:
        parts.append(lead.rstrip())
        parts.append("")
    if role:
        parts.append(role.rstrip())
        parts.append("")
    parts.append(shared_rules_markdown().rstrip())
    parts.append("")
    if footer:
        parts.append(footer.rstrip())
        parts.append("")
    text = "\n".join(parts)
    if not text.endswith("\n"):
        text += "\n"
    return text


